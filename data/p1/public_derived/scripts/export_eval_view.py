"""Export the P1 resume-eval view to `c-evaluation-draft-1`.

Only rows with `resume_loss_mask == 1` are exported. Those rows have the
outcome outside the observed history, so the view is safe to hand to a model.
Everything else stays in `processed/p1_combined.jsonl` and is documented as
censored or as a state-prediction cutoff.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from common import write_lf

ROOT = Path(__file__).resolve().parents[1]
COMBINED = ROOT / "processed" / "p1_combined.jsonl"
OUT = ROOT / "eval"

SPLIT_MAP = {"train": "train", "val": "dev", "test": "test"}

# (event_type, semantic.kind, action_status)
EVENT_MAP = {
    "start_goal": ("goal_started", "goal_started", None),
    "interruption": ("interruption_started", "interruption_started", None),
    "background_fact": ("background_fact", "background_fact", None),
}

MAPPING_NOTES = """\
# P1 resume-eval view -> `c-evaluation-draft-1`

Generated by `python scripts/export_eval_view.py`. Source of truth is
`processed/p1_combined.jsonl`; this view adds no labels and edits none.

## What is exported

All rows with `resume_loss_mask == 1` and a non-empty `task_steps`:

| source | rows | resume | not_resume |
|---|---:|---:|---:|
{per_source}

Excluded from this view (and why):

| rows | reason |
|---:|---|
| {n_censored} | `p1_censoring_status="censored"`: the window does not cover the outcome, so `p1_observed_resume` is `null`, not `false` |
| {n_state_pred} | observed label, but the recovery/completion action is inside the observed history (`cutoff_kind` in `recovery`/`completion`); useful for state prediction, not blind resume |
| {n_ibt} | InterruptBench: no step decomposition (`task_steps=[]`) and every row is censored; `c-evaluation-draft-1` requires non-empty `task_steps`, so a V-only view needs a C-side protocol extension |

## Field mapping decisions

* `split`: source `val` -> protocol `dev`. `test` stays held out. `train` is the
  only split a model may fit on.
* `time` and `cutoff` are **ordinal event indices** (0..n-1), not wall-clock
  time. The upstream P1 package carries no timestamps; ordered indices preserve
  the only temporal information that exists.
* `horizon`: `observation_horizon.planned` mapped to
  `{{type: decision_opportunities, value: planned}}`. The native unit differs by
  source (IHBench assistant turns / one response, REBOOT annotated frames); it
  is **not** comparable to P0's decision-opportunity horizon.
* `certainty`: provenance tier, not a probability. `1.0` for
  `original_annotation`, `0.5` for `rule_mapping`.
* `world_effect`: `null`. P1 does not publish objective world snapshots per event.
* `observer_evidence`: the upstream event `text` (never empty in this view).
* `person_access_evidence.understood`: always `null`; P1 publishes no
  comprehension labels. `status` is copied from the upstream `person_access`.
* `task_graph.edges`: empty. P1 publishes no step-dependency annotations; the
  node set equals `task_steps`.
* `purpose = "public_derived_p1"`. Never relabel as `synthetic_integration_fixture`.
* `dataset_layer = "P1"` in every gold row. Do not mix with P0 in one evaluation.

## Labels

* `resume_label` / `resume_step`: `p1_observed_resume` / `p1_resume_step`.
  `resume_step` is always a member of `task_steps` in this view.
* `state_labels`: `V` only. `C`, `F`, `A`, `B`, `Q` are not carried here:
  the rule-mapped values were withdrawn in the 2026-10-23 revision
  (`state_withdrawn`, rules T5-T9 / R2-R8 / B7-B12) and only `V` survives with
  per-row evidence. Do not compute T3 on this view.
* `state_evidence`: the upstream `evidence_trace` (event ids), verified to be a
  subset of the exported `events`.
* `window_complete`: `true`; these are exactly the rows whose outcome window is
  observed. The 1,951 censored rows are outside this view.
* `annotation_source`: upstream annotation + deterministic rule conversion.

## Known ceiling

`observed_not_resume` is {n_not_resume} rows, all from IHBench (the second actor
is the dataset's released GPT-4o Audio reference answer, not a human). There is
no human P1 record and no other negative source; a low not-resume recall is a
property of this ceiling, not a model defect. Report metrics per
`source_dataset` and never merge P0 with P1.
"""


def map_event(event: dict, goal_id: str, index: int) -> dict:
    kind = event["event_type"]
    if kind == "progress":
        c_type = "task_action" if event.get("step_id") else "progress"
        semantic_kind = "task_action" if event.get("step_id") else "task_progress"
        action_status = "in_progress" if event.get("step_id") else None
    else:
        c_type, semantic_kind, action_status = EVENT_MAP[kind]
    mapped = {
        "event_id": event["event_id"],
        "time": index,
        "actor": event["actor"],
        "event_type": c_type,
        "goal_id": goal_id,
        "step_id": event.get("step_id"),
        "world_effect": None,
        "observer_evidence": event["text"],
        "person_access_evidence": {"status": event["person_access"], "understood": None},
        "source": event["source"],
        "certainty": 1.0 if event["source"] == "original_annotation" else 0.5,
        "semantic": {"kind": semantic_kind},
    }
    if action_status is not None:
        mapped["action_status"] = action_status
    return mapped


def to_input(row: dict) -> dict:
    events = [map_event(event, row["goal_id"], index) for index, event in enumerate(row["observed_events"])]
    planned = row["observation_horizon"].get("planned")
    return {
        "sample_id": row["sample_id"],
        "base_story_id": row["base_story_id"],
        "person_id": row["actor_id"],
        "task_family": row["goal_id"],
        "domain": row["source_dataset"],
        "split": SPLIT_MAP[row["split"]],
        "purpose": "public_derived_p1",
        "observation": {
            "target_person": row["actor_id"],
            "goal_id": row["goal_id"],
            "task_steps": list(row["task_steps"]),
            "task_graph": {"nodes": list(row["task_steps"]), "edges": []},
            "cutoff": int(len(events) - 1),
            "horizon": {"type": "decision_opportunities", "value": max(1, int(planned or 1))},
            "events": events,
        },
    }


def to_label(row: dict) -> dict:
    return {
        "sample_id": row["sample_id"],
        "dataset_layer": "P1",
        "resume_label": "resume" if row["p1_observed_resume"] is True else "not_resume",
        "resume_step": row["p1_resume_step"],
        "state_labels": {"V": row["state_at_cutoff"]["V"]},
        "state_evidence": {"V": list(row["evidence_trace"])},
        "window_complete": True,
        "annotation_source": "upstream annotation + deterministic rule conversion; B delivery 2026-10-23",
    }


def write_jsonl(path: Path, rows: list[dict]) -> None:
    write_lf(path, "\n".join(json.dumps(row, ensure_ascii=False, sort_keys=True) for row in rows) + "\n")


def main() -> int:
    rows = [json.loads(line) for line in COMBINED.read_text(encoding="utf-8").splitlines() if line.strip()]
    eligible = [row for row in rows if row.get("resume_loss_mask") == 1]
    assert all(row["task_steps"] for row in eligible), "C protocol requires non-empty task_steps"
    assert all(row["evidence_trace"] for row in eligible), "non-UNKNOWN V requires evidence"
    eligible.sort(key=lambda row: row["sample_id"])

    inputs = [to_input(row) for row in eligible]
    labels = [to_label(row) for row in eligible]
    OUT.mkdir(parents=True, exist_ok=True)
    write_jsonl(OUT / "inputs.jsonl", inputs)
    write_jsonl(OUT / "labels.jsonl", labels)

    per_source = Counter((row["source_dataset"], row["p1_observed_resume"]) for row in eligible)
    sources = sorted({row["source_dataset"] for row in eligible})
    table = "\n".join(
        f"| {source} | {per_source[(source, True)] + per_source[(source, False)]} | "
        f"{per_source[(source, True)]} | {per_source[(source, False)]} |"
        for source in sources
    )
    censored = sum(1 for row in rows if row["p1_censoring_status"] == "censored")
    state_pred = sum(
        1 for row in rows if row.get("p1_observed_resume") is not None and row.get("resume_loss_mask") == 0
    )
    interrupts = sum(1 for row in rows if row["source_dataset"] == "InterruptBench")
    not_resume = sum(1 for row in eligible if row["p1_observed_resume"] is False)
    write_lf(
        OUT / "MAPPING.md",
        MAPPING_NOTES.format(
            per_source=table,
            n_censored=censored,
            n_state_pred=state_pred,
            n_ibt=interrupts,
            n_not_resume=not_resume,
        ),
    )
    print(f"wrote {len(inputs)} inputs / {len(labels)} labels to {OUT.relative_to(ROOT)}")
    print("by source:", {source: sum(per_source[(source, value)] for value in (True, False)) for source in sources})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
